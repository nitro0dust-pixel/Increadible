#!/usr/bin/env node
/**
 * Writes docs/GATEWAY-CANDIDATES.md from the candidate store (gated catalog, step 4) and the catalog: what the 2,000-odd
 * candidates are, per category and listed auth, and how the catalog's own APIs appear in the list. It is material for the owner's
 * choice of what to gate next; it selects nothing. `tests/gateway-candidates.test.ts` fails when the document and this output differ.
 *
 *   npm run build && node scripts/candidate-report.js        (reads the catalog from dist/)
 */
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const STORE = "features/09-api-gateway/data/candidates-public-apis.json";
const DOC = "docs/GATEWAY-CANDIDATES.md";

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const site = (url) => new URL(url).hostname.replace(/^(www|api|en)\./, "");
const pct = (n, d) => (d === 0 ? "0%" : `${((100 * n) / d).toFixed(1)}%`);

/**
 * The candidate that is the same API as a catalog entry: one whose documentation host matches the catalog's endpoint or docs host;
 * only when none does, one with the same name. (By name alone, "WeatherAPI" also matches an unrelated project called "weather-api".)
 */
function matchCatalog(definition, candidates) {
  const hosts = [definition.endpoint, definition.docs_url].filter(Boolean).map(site);
  const byHost = candidates.filter((c) => hosts.some((h) => site(c.docs_url) === h || site(c.docs_url).endsWith(`.${h}`)));
  if (byHost.length > 0) return byHost;
  return candidates.filter((c) => norm(c.name) === norm(definition.name));
}

const LISTED_TO_CLASS = { No: "none", apiKey: "api_key", "X-Mashape-Key": "api_key", OAuth: "oauth" };

function report(store, catalog) {
  const all = store.candidates;
  const keyless = all.filter((c) => c.listed_auth === "No");
  const lines = [];
  const out = (s = "") => lines.push(s);

  out("# Gateway candidates: what the seed list holds");
  out();
  out("<!-- Generated by `node scripts/candidate-report.js` from the candidate store and the catalog. Do not edit here: a test");
  out("     fails when this file and the generator's output differ. -->");
  out();
  out(`Material for choosing what to gate next (gated catalog, \`docs/GATEWAY-GATED-CATALOG.md\`). It **selects nothing**: every row`);
  out("below is a listing, not evidence that an API works, and a listed auth is the list's claim, not a classification (gate 2).");
  out();
  out(`Source: \`${STORE}\`, from the ${store.source} list fetched on ${store.fetched_on} (SHA-256 \`${store.source_sha256.slice(0, 8)}...\`, ${store.licence.split("\n")[0]}).`);
  out();
  out("## 1. Totals");
  out();
  out("| | Candidates | Share |");
  out("|---|---|---|");
  out(`| All | ${all.length} | 100% |`);
  for (const [auth, n] of Object.entries(store.counts.listed_auth).sort((a, b) => b[1] - a[1])) out(`| Listed auth \`${auth}\` | ${n} | ${pct(n, all.length)} |`);
  out(`| Listed with no auth **and** HTTPS | ${keyless.filter((c) => c.https).length} | ${pct(keyless.filter((c) => c.https).length, all.length)} |`);
  out(`| Source rows not readable (listed in the store) | ${store.skipped.length} | |`);
  out();
  out("## 2. The catalog's own APIs in the list");
  out();
  out("Matched by documentation host, or by name when no host matches. A difference between the two auth columns is exactly what");
  out("gate 2 is for: the catalog's value was set by a person (and, for the keyless four, used live on 2026-10-10); the list's was not.");
  out();
  out("| Catalog API | Catalog auth | In the list as | Listed auth | Agrees |");
  out("|---|---|---|---|---|");
  for (const { definition } of catalog) {
    const m = matchCatalog(definition, all);
    if (m.length === 0) {
      out(`| ${definition.id} | ${definition.auth} | not found | | |`);
      continue;
    }
    for (const c of m) {
      const agrees = LISTED_TO_CLASS[c.listed_auth] === definition.auth;
      out(`| ${definition.id} | ${definition.auth} | \`${c.source_id}\` | \`${c.listed_auth}\` | ${agrees ? "yes" : "**no**"} |`);
    }
  }
  out();
  out("## 3. Per category");
  out();
  out("\"Keyless\" means listed with no auth. A first batch to gate would most likely come from the last two columns: no key to");
  out("store (where keys live is an open owner decision, `GATEWAY.md`) and HTTPS (the catalog accepts https endpoints only).");
  out();
  out("| Category | Candidates | Keyless | Keyless and HTTPS |");
  out("|---|---|---|---|");
  const categories = [...new Set(all.map((c) => c.category))].sort((a, b) => a.localeCompare(b));
  for (const cat of categories) {
    const inCat = all.filter((c) => c.category === cat);
    const k = inCat.filter((c) => c.listed_auth === "No");
    out(`| ${cat} | ${inCat.length} | ${k.length} | ${k.filter((c) => c.https).length} |`);
  }
  out();
  out("## 4. What choosing needs");
  out();
  out("For each API chosen, the gates of `docs/GATEWAY-GATED-CATALOG.md` section 3: a person pins the base URL and confirms the");
  out("auth class, the terms are read and recorded, a health probe and a recorded contract are written; only then is it added to");
  out("`catalog.ts`, and it answers sample data until it is also listed in `GATEWAY_LIVE_APIS`.");
  return `${lines.join("\n")}\n`;
}

function main() {
  const dist = path.join(root, "dist", "features", "09-api-gateway", "src", "catalog.js");
  if (!fs.existsSync(dist)) {
    console.error("candidate-report: dist/ is missing: run npm run build first");
    process.exit(2);
  }
  const { CATALOG } = require(dist);
  const store = JSON.parse(fs.readFileSync(path.join(root, STORE), "utf8"));
  fs.writeFileSync(path.join(root, DOC), report(store, CATALOG));
  console.log(`candidate-report: ${DOC} written (${store.candidates.length} candidates, ${CATALOG.length} catalog APIs)`);
}

if (require.main === module) main();
module.exports = { report, matchCatalog, DOC, STORE };
